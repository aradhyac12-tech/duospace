#!/usr/bin/env node
/**
 * patch-android-signing.mjs
 *
 * `npx cap add android` generates android/app/build.gradle with no release
 * signingConfig at all — buildTypes.release just has no signingConfig line,
 * which makes `assembleRelease` produce an UNSIGNED apk (installable by
 * nobody, and easy to mistake for a successful build since Gradle exits 0).
 *
 * This script wires buildTypes.release.signingConfig to a signingConfigs
 * block pointed at the keystore CI decoded to android/app/release.keystore.
 * It reads credentials from env vars, not from committed files.
 *
 * Preconditions (checked by the calling CI step, not here):
 *   - android/app/release.keystore exists (base64-decoded from a secret)
 *   - the alias actually exists in that keystore (verified with `keytool`)
 *
 * Idempotent: safe to re-run, replaces its own previously-inserted block
 * instead of duplicating it.
 *
 * Required env vars: ANDROID_KEYSTORE_PASSWORD, ANDROID_KEY_ALIAS, ANDROID_KEY_PASSWORD
 * (ANDROID_KEYSTORE_BASE64 is consumed by the CI step before this script
 * runs, not read here — this script only needs the decoded file's path.)
 *
 * Usage: node scripts/patch-android-signing.mjs
 */

import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { join } from "node:path";

const ROOT = process.cwd();
const GRADLE_PATH = join(ROOT, "android", "app", "build.gradle");
const KEYSTORE_PATH = join(ROOT, "android", "app", "release.keystore");

const { ANDROID_KEYSTORE_PASSWORD, ANDROID_KEY_ALIAS, ANDROID_KEY_PASSWORD } = process.env;

function fail(msg) {
  console.error(`[patch-android-signing] \u274c ${msg}`);
  process.exit(1);
}

if (!existsSync(GRADLE_PATH)) fail(`${GRADLE_PATH} not found — run this after \`cap add android\` / \`cap sync\`.`);
if (!existsSync(KEYSTORE_PATH)) fail(`${KEYSTORE_PATH} not found — decode the keystore secret to this path before running.`);
if (!ANDROID_KEYSTORE_PASSWORD || !ANDROID_KEY_ALIAS || !ANDROID_KEY_PASSWORD) {
  fail("ANDROID_KEYSTORE_PASSWORD, ANDROID_KEY_ALIAS, and ANDROID_KEY_PASSWORD must all be set in the environment.");
}

const MARKER_START = "// DUOSPACE RELEASE SIGNING (auto-generated by scripts/patch-android-signing.mjs — do not hand-edit)";
const MARKER_END = "// END DUOSPACE RELEASE SIGNING";

const signingBlock = `    ${MARKER_START}
    signingConfigs {
        release {
            storeFile file("release.keystore")
            storePassword System.getenv("ANDROID_KEYSTORE_PASSWORD")
            keyAlias System.getenv("ANDROID_KEY_ALIAS")
            keyPassword System.getenv("ANDROID_KEY_PASSWORD")
        }
    }
    ${MARKER_END}
`;

let gradle = readFileSync(GRADLE_PATH, "utf8");

// Remove any previously-inserted block so re-runs don't duplicate it.
const blockRe = new RegExp(`\\s*${MARKER_START}[\\s\\S]*?${MARKER_END}\\n`, "m");
gradle = gradle.replace(blockRe, "\n");

const androidBlockMatch = gradle.match(/android\s*\{/);
if (!androidBlockMatch) fail("Could not find `android {` block in build.gradle — template may have changed shape, patch manually.");

const insertAt = androidBlockMatch.index + androidBlockMatch[0].length;
gradle = gradle.slice(0, insertAt) + "\n" + signingBlock + gradle.slice(insertAt);

// Point buildTypes.release at the signing config we just added, without
// disturbing whatever else cap-generated buildTypes.release already has
// (minifyEnabled, proguard files, etc.).
if (/buildTypes\s*\{[\s\S]*?release\s*\{/.test(gradle)) {
  if (!/release\s*\{[^}]*signingConfig\s+signingConfigs\.release/.test(gradle)) {
    gradle = gradle.replace(/(buildTypes\s*\{[\s\S]*?release\s*\{)/, `$1\n            signingConfig signingConfigs.release`);
  }
} else {
  fail("Could not find buildTypes { release { ... } } block in build.gradle — patch manually.");
}

writeFileSync(GRADLE_PATH, gradle);
console.log("[patch-android-signing] \u2705 build.gradle: release signingConfig wired to android/app/release.keystore");
